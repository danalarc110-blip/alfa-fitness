function phpJson(body) {
    const result = spawnSync(php, [], {cwd: root, env, encoding: 'utf8', windowsHide: true, input: `<?php require 'vendor/autoload.php'; $app = require 'bootstrap/app.php'; $app->make(Illuminate\\Contracts\\Console\\Kernel::class)->bootstrap(); if (config('database.default') !== 'sqlite' || config('database.connections.sqlite.database') !== getenv('DB_DATABASE') || config('database.connections.sqlite.url')) throw new RuntimeException('Disposable database required.'); ${body}`});
    assert.equal(result.status, 0, result.stderr);
    return JSON.parse(result.stdout);
}
