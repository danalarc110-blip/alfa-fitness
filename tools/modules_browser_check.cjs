// Exercises real compiled assets against a disposable SQLite database only.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const net = require('node:net');
const {spawn, spawnSync} = require('node:child_process');
const puppeteer = require('puppeteer-core');
const {acceptPrivacyPuppeteer} = require('./privacy_qa.cjs');
const root = path.resolve(__dirname, '..');
const php = process.env.ALPHA_QA_PHP || 'C:/xampp/php/php.exe';
const chrome = process.env.ALPHA_QA_BROWSER || 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const soloPOS = process.argv.includes('--pos-only');
const cfg = JSON.parse(fs.readFileSync(path.join(root, 'storage/app/private/modules-qa.json'), 'utf8'));
assert.equal(fs.realpathSync.native(path.dirname(cfg.database)).toLowerCase(), fs.realpathSync.native(os.tmpdir()).toLowerCase());
assert.ok(path.basename(cfg.database).startsWith('alpha-modules-qa-'));
assert.equal(cfg.url, 'http://127.0.0.1:8031');
const out = path.join(root, 'storage/app/private/modules-check');
fs.mkdirSync(out, {recursive: true});
const env = {...process.env, APP_ENV: 'local', APP_URL: cfg.url, APP_DEBUG: 'false', DB_CONNECTION: 'sqlite', DB_DATABASE: cfg.database, DB_URL: '', SESSION_DRIVER: 'file', SESSION_COOKIE: 'alpha_modules_qa', CACHE_STORE: 'array', MAIL_MAILER: 'array', QUEUE_CONNECTION: 'sync'};
const checks = [];
const passed = check => { checks.push(check); console.log('PASS ' + check); };
let browser, server;
const portAvailable = () => new Promise((resolve, reject) => {
    const probe = net.createServer();
    probe.once('error', reject);
    probe.listen(8031, '127.0.0.1', () => probe.close(resolve));
});

(async () => {
    await portAvailable();
    const log = fs.openSync(path.join(out, 'server.log'), 'a');
    server = spawn(php, ['-S', '127.0.0.1:8031', '-t', 'public', 'tools/qa_router.php'], {cwd: root, env, windowsHide: true, stdio: ['ignore', log, log]});
    fs.closeSync(log);
    browser = await puppeteer.launch({executablePath: chrome, headless: true});
    const errors = [];
    const context = await browser.createBrowserContext();
    const page = await context.newPage();
    page.setDefaultNavigationTimeout(60000);
    await page.setViewport({width: 1440, height: 1000});
    await page.emulateMediaFeatures([{name: 'prefers-reduced-motion', value: 'reduce'}]);
    page.on('pageerror', error => errors.push(error.message));
    const visit = async (route, status = 200) => {
        const response = await page.goto(cfg.url + route, {waitUntil: 'domcontentloaded'});
        assert.equal(response.status(), status, route);
        if (status === 200) assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Page overflow: ' + route);
    };
    const body = () => page.$eval('body', node => node.innerText);
    const fill = async (selector, value) => {
        await page.$eval(selector, node => {node.value = '';});
        await page.type(selector, value);
    };
    const clickNavigate = async selector => Promise.all([page.waitForNavigation({waitUntil: 'domcontentloaded'}), page.click(selector)]);
    const keyNavigate = async selector => {
        await page.focus(selector);
        await Promise.all([page.waitForNavigation({waitUntil: 'domcontentloaded'}), page.keyboard.press('Enter')]);
    };
    const login = async (email, cliente = false) => {
        await visit('/login');
        await acceptPrivacyPuppeteer(page);
        if (cliente) await page.click('#tab-btn-clientes');
        const form = cliente ? '#form-cliente-login' : '#form-usuario';
        await fill(form + (cliente ? ' [name=correo]' : ' [name=email]'), email);
        await fill(form + ' [name=password]', cfg.password);
        await clickNavigate(form + ' [type=submit]');
        assert.ok(page.url().endsWith(cliente ? '/cliente/dashboard' : '/dashboard'));
    };
    const logout = async () => {
        await visit('/configuracion');
        await page.evaluate(async () => {
            const token = document.querySelector('meta[name=csrf-token]').content;
            await fetch('/logout', {method: 'POST', headers: {'X-CSRF-TOKEN': token}});
        });
        await context.deleteCookie(...await context.cookies());
    };

    if (!soloPOS) {
    await login('cliente-qa@example.test', true);
    await visit('/productos');
    let text = await body();
    assert.ok(text.includes('Para comprar este producto, acércate a recepción. La venta la realiza la secretaria'));
    assert.ok(text.includes('Agotado'));
    assert.ok(!text.includes('Oculto QA') && !text.includes('Stock crítico'));
    assert.equal(await page.$$eval('[name=stock], [data-stock], [href="' + cfg.url + '/ventas"]', nodes => nodes.length), 0);
    assert.equal(await page.$$eval('article img', nodes => nodes.every(node => node.alt && node.complete && node.naturalWidth > 0)), true);
    await page.screenshot({path: path.join(out, 'cliente-productos-desktop.png'), fullPage: true});
    await visit('/ventas', 403);
    passed('Client catalog, local images and forbidden sales');

    await visit('/entrenadores');
    assert.equal(await page.$$eval('[data-mi-entrenador]', nodes => nodes.length), 1);
    assert.equal(await page.$eval('[data-mi-entrenador]', node => node.dataset.miEntrenador), String(cfg.entrenador_id));
    assert.ok(!(await body()).includes('entrenador@example.test'));
    assert.ok((await body()).includes('Sin calificaciones'));
    assert.ok(!(await body()).includes('Entrenador inactivo QA'));
    const star = '.star-rating[data-entrenador-id="' + cfg.entrenador_id + '"]';
    await keyNavigate(star + ' button[value="4"]');
    assert.equal(await page.$eval(star, node => node.dataset.current), '4');
    await keyNavigate(star + ' button[value="5"]');
    assert.equal(await page.$eval(star, node => node.dataset.current), '5');
    assert.ok((await body()).includes('1 valoración'));
    await page.setViewport({width: 390, height: 844});
    await visit('/entrenadores');
    await page.screenshot({path: path.join(out, 'cliente-entrenadores-mobile.png'), fullPage: true});
    await visit('/productos');
    await page.focus('#alpha-hamburger-btn');
    await page.keyboard.press('Enter');
    assert.equal(await page.$eval('#alpha-hamburger-btn', node => node.getAttribute('aria-expanded')), 'true');
    await page.keyboard.press('Escape');
    assert.equal(await page.$eval('#alpha-hamburger-btn', node => node.getAttribute('aria-expanded')), 'false');
    passed('Ratings update without duplicate votes, mobile and keyboard navigation');
    await logout();

    await login('entrenador@example.test');
    await visit('/entrenador/clientes');
    assert.equal(await page.$$eval('article[data-cliente-id]', nodes => nodes.length), 1);
    assert.ok((await body()).includes('Fuerza QA') && (await body()).includes('Movilidad QA'));
    assert.ok(!(await body()).includes('Cliente ajeno QA'));
    await fill('#buscar-cliente', 'vinculado');
    await keyNavigate('form[role=search] button[type=submit]');
    assert.equal(await page.$$eval('article[data-cliente-id]', nodes => nodes.length), 1);
    await visit('/entrenador/clientes/' + cfg.cliente_id);
    await visit('/entrenador/clientes/' + cfg.cliente_id + '/progreso');
    await page.screenshot({path: path.join(out, 'entrenador-progreso-mobile.png'), fullPage: true});
    await visit('/entrenador/clientes/' + cfg.ajeno_id, 403);
    await visit('/entrenador/clientes/' + cfg.ajeno_id + '/progreso', 403);
    await visit('/ventas', 403);
    passed('Trainer clients deduplicated, search, details, progress and forbidden foreign URLs');
    await logout();
    }

    await login('secretaria@example.test');
    await visit('/productos');
    assert.equal(await page.$$eval('[name=stock]', nodes => nodes.length), 0);
    await page.setViewport({width: 1440, height: 1000});
    await visit('/ventas');
    await page.waitForSelector('#venta-nueva:not(.hidden)');
    assert.equal(await page.$eval('#venta-ir-carrito', node => getComputedStyle(node).display), 'none');
    assert.equal(await page.$eval('#venta-revisar', node => node.disabled), true);
    await page.click('[data-venta-categoria="Bebidas"]');
    assert.equal(await page.$$eval('.venta-producto:not(.hidden)', nodes => nodes.length), 2);
    await page.click('[data-venta-categoria=""]');
    assert.equal(await page.$eval('#venta-registrar', node => getComputedStyle(node).display), 'none');
    assert.notEqual(await page.$eval('#venta-revisar', node => getComputedStyle(node).display), 'none');
    await fill('#venta-busqueda', 'bebidas');
    await page.keyboard.press('Enter');
    assert.equal(await page.$$eval('.item-fila', nodes => nodes.length), 0);
    const add = '.venta-producto:not(.hidden) [data-anadir-producto]';
    assert.equal(await page.$$eval(add, nodes => nodes.length), 2);
    await page.focus(add);
    await page.keyboard.press('Enter');
    await page.keyboard.press('Enter');
    assert.equal(await page.$$eval('.item-fila', nodes => nodes.length), 1);
    assert.equal(await page.$eval('.input-cantidad', node => node.value), '2');
    assert.equal(await page.$eval('#venta-conteo', node => node.textContent), '2 unidades');
    await page.click('nav [data-venta-ir="historial"]');
    assert.equal(await page.$eval('#venta-nueva', node => node.classList.contains('hidden')), true);
    await page.click('nav [data-venta-ir="nueva"]');
    assert.equal(await page.$eval('.input-cantidad', node => node.value), '2');
    await page.click('.cantidad-mas');
    assert.equal(await page.$eval('.input-cantidad', node => node.value), '3');
    await page.click('.cantidad-menos');
    await fill('.input-cantidad', '1');
    assert.equal(await page.$eval('.cantidad-menos', node => node.disabled), true);
    await fill('.input-cantidad', '2');
    assert.equal(await page.$eval('.cantidad-menos', node => node.disabled), false);
    await fill('.input-cantidad', await page.$eval('.input-cantidad', node => node.max));
    assert.equal(await page.$eval('.cantidad-mas', node => node.disabled), true);
    await fill('.input-cantidad', '2');
    assert.equal(await page.$eval('.cantidad-mas', node => node.disabled), false);
    await page.select('#venta-cliente', String(cfg.cliente_id));
    await page.select('#venta-metodo', 'Transferencia');
    await fill('#venta-notas', 'Venta presencial QA');
    const successfulPayload = await page.$eval('#form-venta', form => [...new FormData(form).entries()]);
    await page.screenshot({path: path.join(out, 'secretaria-venta-desktop.png'), fullPage: true});
    await page.click('#venta-revisar');
    await page.click('#venta-editar');
    assert.equal(await page.$eval('.input-cantidad', node => node.value), '2');
    await page.click('#venta-revisar');
    assert.equal(await page.$eval('#venta-revisar', node => getComputedStyle(node).display), 'none');
    assert.notEqual(await page.$eval('#venta-registrar', node => getComputedStyle(node).display), 'none');
    assert.equal(await page.$eval('#venta-edicion', node => getComputedStyle(node).display), 'none');
    assert.ok((await page.$eval('#venta-revision', node => node.innerText)).includes('Transferencia'));
    await page.screenshot({path: path.join(out, 'secretaria-venta-revision-desktop.png'), fullPage: true});
    await clickNavigate('#venta-registrar');
    assert.ok((await body()).includes('Venta registrada exitosamente'));
    const retryStatus = await page.evaluate(async payload => (await fetch('/ventas', {method: 'POST', body: new URLSearchParams(payload), headers: {Accept: 'application/json'}})).status, successfulPayload);
    assert.equal(retryStatus, 200);
    const receipt = await page.$('a[href*="/comprobante"]');
    assert.ok(receipt);
    const receiptUrl = await receipt.evaluate(node => node.href);
    await visit(new URL(receiptUrl).pathname);
    assert.ok((await body()).includes('Transferencia'));
    assert.ok(await page.$('form[action$="/enviar-correo"]'));
    await visit('/ventas?vista=historial&metodo=Transferencia');
    assert.equal(await page.$eval('#venta-historial', node => node.classList.contains('hidden')), false);
    await clickNavigate('#venta-historial a[href$="vista=historial"]');
    assert.equal(await page.$eval('#venta-historial', node => node.classList.contains('hidden')), false);
    await clickNavigate('#venta-historial button[type=submit]');
    assert.equal(await page.$eval('#venta-historial', node => node.classList.contains('hidden')), false);
    passed('POS search, grouped quantity controls, review, registration, retry and receipt');

    await page.setViewport({width: 390, height: 844});
    await visit('/ventas');
    assert.notEqual(await page.$eval('#venta-ir-carrito', node => getComputedStyle(node).display), 'none');
    await page.screenshot({path: path.join(out, 'secretaria-venta-mobile.png'), fullPage: true});
    await page.click('[data-anadir-producto]:not(:disabled)');
    await page.click('#venta-ir-carrito');
    await page.select('#venta-cliente', String(cfg.cliente_id));
    await page.select('#venta-metodo', 'Tarjeta');
    await fill('#venta-notas', 'Conservar al corregir');
    await page.$eval('.input-cantidad', node => {node.value = '999'; node.dispatchEvent(new Event('input', {bubbles: true}));});
    const failedUuid = await page.$eval('[name=venta_uuid]', node => node.value);
    await Promise.all([page.waitForNavigation({waitUntil: 'domcontentloaded'}), page.$eval('#form-venta', form => form.submit())]);
    assert.ok((await body()).includes('Stock insuficiente'));
    await page.waitForSelector('#venta-nueva:not(.hidden)');
    assert.equal(await page.$eval('[name=venta_uuid]', node => node.value), failedUuid);
    assert.equal(await page.$eval('.input-cantidad', node => node.value), '999');
    assert.equal(await page.$eval('#venta-cliente', node => node.value), String(cfg.cliente_id));
    assert.equal(await page.$eval('#venta-metodo', node => node.value), 'Tarjeta');
    assert.equal(await page.$eval('#venta-notas', node => node.value), 'Conservar al corregir');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({path: path.join(out, 'secretaria-venta-error-mobile.png'), fullPage: true});
    await page.focus('.quitar-producto');
    await page.keyboard.press('Enter');
    assert.equal(await page.$$eval('.item-fila', nodes => nodes.length), 0);
    assert.equal(await page.$eval('#gran-total', node => node.textContent), '$0.00');
    assert.equal(await page.$eval('#venta-revisar', node => node.disabled), true);
    await page.focus('nav [data-venta-ir="historial"]');
    await page.keyboard.press('Enter');
    assert.equal(await page.$eval('#venta-nueva', node => node.classList.contains('hidden')), true);
    passed('POS stock error preserves inputs and UUID; mobile cart shortcut, keyboard removal and history navigation');

    if (!soloPOS) {
        await logout();
        await login('administrador@example.test');
        await visit('/entrenadores');
        assert.ok((await body()).includes('entrenador@example.test'));
        assert.ok((await body()).includes('las invitaciones no se entregan'));
        await clickNavigate('article[data-entrenador-id="' + cfg.entrenador_id + '"] a[href*="entrenador_id="]');
        assert.equal(await page.$eval('#filtro-entrenador', node => node.value), String(cfg.entrenador_id));
        assert.equal(await page.$$eval('article[data-cliente-id]', nodes => nodes.length), 1);
        assert.ok((await body()).includes('Asignada por: Entrenador QA'));
        assert.ok(!(await body()).includes('Cliente ajeno QA'));
        await page.screenshot({path: path.join(out, 'admin-asignaciones-mobile.png'), fullPage: true});
        passed('Admin trainer account visibility and filtered client assignments');
    }

    assert.deepEqual(errors, [], 'Browser JavaScript errors');
    const verification = spawnSync(php, [], {cwd: root, env, encoding: 'utf8', input: '<?php require "vendor/autoload.php"; $app=require "bootstrap/app.php"; $app->make(Illuminate\\Contracts\\Console\\Kernel::class)->bootstrap(); echo json_encode(["ventas"=>App\\Models\\Venta::count(),"detalles"=>App\\Models\\DetalleVenta::count(),"votos"=>App\\Models\\EntrenadorCalificacion::count(),"estrellas"=>App\\Models\\EntrenadorCalificacion::value("estrellas")]);'});
    assert.equal(verification.status, 0);
    const data = JSON.parse(verification.stdout);
    assert.deepEqual(data, soloPOS ? {ventas: 1, detalles: 1, votos: 0, estrellas: null} : {ventas: 1, detalles: 1, votos: 1, estrellas: 5});
    fs.writeFileSync(path.join(out, soloPOS ? 'results-pos.json' : 'results.json'), JSON.stringify({checks, database: data, jsErrors: errors, viewport: ['1440x1000', '390x844']}, null, 2));
    console.log('PASS database: no duplicate sale or detail' + (soloPOS ? '' : ', one updated trainer rating') + '; no JS errors');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
    if (server) server.kill();
    if (browser) await browser.close();
});
